package io.github.valtairnascimento.campaignforms.exception;

import com.liferay.portal.kernel.exception.PortalException;

public class PageTemplateConfigurationException extends PortalException {
	public PageTemplateConfigurationException() {
	}

	public PageTemplateConfigurationException(String msg) {
		super(msg);
	}

	public PageTemplateConfigurationException(String msg, Throwable throwable) {
		super(msg, throwable);
	}

	public PageTemplateConfigurationException(Throwable throwable) {
		super(throwable);
	}

}
